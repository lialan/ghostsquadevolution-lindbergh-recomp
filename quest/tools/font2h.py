#!/usr/bin/env python3
"""font2h.py <font.ttf> <out.h> - the settings menu's font (xr_menu.c): printable
ASCII as 8-bit coverage, one fixed-size cell a character. Made from DejaVu Sans
Mono (Bitstream Vera licence: free to use and redistribute, see its LICENSE)."""
import sys
from PIL import Image, ImageDraw, ImageFont
W, H, SIZE = 20, 34, 28
font = ImageFont.truetype(sys.argv[1], SIZE)
cells = []
for ch in range(32, 127):
    im = Image.new('L', (W, H), 0)
    ImageDraw.Draw(im).text((1, 1), chr(ch), fill=255, font=font)
    cells.append(im.tobytes())
with open(sys.argv[2], 'w') as f:
    f.write('/* Generated by quest/tools/font2h.py from DejaVu Sans Mono (Bitstream Vera licence). */\n')
    f.write('#define FONT_W %d\n#define FONT_H %d\n#define FONT_FIRST 32\n#define FONT_COUNT %d\n' % (W, H, len(cells)))
    f.write('static const unsigned char FONT[FONT_COUNT][FONT_W * FONT_H] = {\n')
    for c in cells:
        f.write('    {' + ','.join(str(b) for b in c) + '},\n')
    f.write('};\n')
