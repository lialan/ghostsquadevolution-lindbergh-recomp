#!/usr/bin/env python3
"""obj2gun.py <model.obj> <out.h> - a gun model for the Quest overlay (xr_overlay.c).

Takes Quaternius' "Ultimate Gun Pack" SubmachineGun_2 (CC0), barrel along +X,
and writes triangles as position, normal, sRGB colour (9 floats a vertex) in
the overlay's gun space: metres, barrel along -Z on the controller's aim ray,
the pistol grip where the old box gun had it. The numbers below were measured
from that model; another model needs its own.
"""
import os, sys

LENGTH = 0.60          # metres, muzzle to stock (an MP5-sized SMG)
BORE_Y = 0.565         # model units: the barrel's axis
GRIP_X = -0.08         # model units: the pistol grip, along the barrel
GRIP_Z = 0.085         # metres behind the aim pose the grip sits

def main(src, out):
    d = os.path.dirname(src)
    v, faces, mats, cur = [], [], {}, None
    for line in open(src):
        p = line.split()
        if not p: continue
        if p[0] == 'mtllib':
            m = None
            for l in open(os.path.join(d, ' '.join(p[1:]))):
                q = l.split()
                if q and q[0] == 'newmtl': m = q[1]
                if q and q[0] == 'Kd': mats[m] = [float(x) for x in q[1:4]]
        elif p[0] == 'v': v.append([float(x) for x in p[1:4]])
        elif p[0] == 'usemtl': cur = p[1]
        elif p[0] == 'f': faces.append(([int(t.split('/')[0]) - 1 for t in p[1:]], cur))
    xs = [p[0] for p in v]
    s = LENGTH / (max(xs) - min(xs))
    x0 = GRIP_X + GRIP_Z / s
    def to_gun(p):      # model (x forward, y up, z across) -> gun (x across, y up, -z forward)
        return (p[2] * s, (p[1] - BORE_Y) * s, -(p[0] - x0) * s)
    def srgb(c):
        return [min(1.0, (max(k, 0.0) ** (1 / 2.2)) * 1.25) for k in c]
    tris = []
    for idx, m in faces:
        col = srgb(mats.get(m, [0.05, 0.05, 0.05]))
        pts = [to_gun(v[i]) for i in idx]
        for k in range(1, len(pts) - 1):
            a, b, c = pts[0], pts[k], pts[k + 1]
            u = [b[i] - a[i] for i in range(3)]; w = [c[i] - a[i] for i in range(3)]
            n = [u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2], u[0] * w[1] - u[1] * w[0]]
            l = sum(x * x for x in n) ** 0.5 or 1.0
            n = [x / l for x in n]
            tris.append([(a, n, col), (b, n, col), (c, n, col)])
    zs = [to_gun(p)[2] for p in v]; ys = [to_gun(p)[1] for p in v]
    with open(out, 'w') as f:
        f.write('/* Generated by quest/tools/obj2gun.py from Quaternius, "Ultimate Gun Pack" (July 2019),\n'
                ' * SubmachineGun_2 - CC0 1.0, https://opengameart.org/content/low-poly-guns-pack\n'
                ' * Gun space, metres: barrel along -Z on the aim ray; position, normal, sRGB colour. */\n')
        f.write('#define GUN_MUZZLE_Z %.4ff\n#define GUN_RAIL_Y %.4ff\n' % (min(zs), (0.90 - BORE_Y) * s))
        f.write('#define GUN_VERTS %d\nstatic const float GUN_MESH[GUN_VERTS * 9] = {\n' % (len(tris) * 3))
        for t in tris:
            for p, n, c in t:
                f.write('    %.4ff, %.4ff, %.4ff, %.3ff, %.3ff, %.3ff, %.3ff, %.3ff, %.3ff,\n' % (*p, *n, *c))
        f.write('};\n')
    print(f'{len(tris)} triangles, scale {s:.4f} m/unit, muzzle z {min(zs):.3f}, y {min(ys):.3f}..{max(ys):.3f}')

main(*sys.argv[1:3])
